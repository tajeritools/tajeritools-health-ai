package ir.tajeritools.healthai

object AnalysisEngine {
    enum class Section { LABS, TRADITIONAL, IRIDOLOGY, TONGUE, PALM }

    fun promptFor(section: Section, extractedText: String = ""): String = when (section) {
        Section.LABS -> """
تو یک دستیار تحلیل آموزشی آزمایش پزشکی هستی. متن OCR گزارش آزمایش را ساختاربندی کن.
قواعد:
- نام آزمایش، مقدار، واحد، محدوده مرجع و علامت H/L را استخراج کن.
- فقط بر اساس محدوده مرجع همان گزارش درباره بالا/پایین بودن صحبت کن.
- روندهای مهم را توضیح بده، اما تشخیص قطعی بیماری نده.
- اگر داده ناقص یا OCR مشکوک است صریحاً بگو.
- مواردی که نیاز به پیگیری سریع پزشکی دارند را با دلیل توضیح بده.
- خروجی فارسی و منظم باشد.

متن گزارش:
$extractedText
""".trimIndent()

        Section.IRIDOLOGY -> """
تصویر عنبیه را از دیدگاه عنبیه‌شناسی سنتی بررسی کن، نه چشم‌پزشکی.
ویژگی‌های قابل مشاهده مثل رنگ، حلقه‌ها، لکه‌ها، شیارها، کریپت‌ها و نواحی ساعت را توصیف کن.
سپس فقط تعبیرهای سنتی محتمل را با عبارت‌هایی مثل «در نقشه‌های سنتی گفته می‌شود» بیان کن.
هیچ بیماری داخلی را از روی عنبیه تشخیص قطعی نده و درصد ساختگی تولید نکن.
اگر کیفیت عکس ناکافی است اول آن را اعلام کن.
در پایان دقیقاً بنویس: «این نتیجه فقط یک احتمال و تفسیر غیرتشخیصی است.»
""".trimIndent()

        Section.TONGUE -> """
تصویر زبان را بررسی کن. ابتدا ویژگی‌های دیداری را جداگانه گزارش کن:
رنگ بدنه، پوشش، ضخامت پوشش، ترک، رطوبت، آثار دندان، نوک و کناره‌ها.
بعد از آن الگوهای سنتی TCM/Ayurveda را فقط به‌عنوان تفسیر سنتی محتمل توضیح بده.
نشانه‌های ظاهری واضحی که ارزش ارزیابی پزشکی دارند را جدا کن، اما بیماری را از روی زبان قطعی تشخیص نده.
در پایان بنویس: «این نتیجه فقط یک احتمال و تفسیر غیرتشخیصی است.»
""".trimIndent()

        Section.PALM -> """
تصویر کف دست را بررسی کن. ویژگی‌های دیداری واقعی مثل رنگ، تورم، خشکی، ترک، ضایعه، تغییر شکل انگشتان یا ناخن‌ها را توصیف کن.
اگر نشانه ظاهری مشخصی نیازمند بررسی پزشکی است، فقط پیشنهاد پیگیری بده.
تعبیرهای کف‌شناسی/سنتی را از یافته‌های پزشکی جدا نگه دار و آن‌ها را صرفاً به‌عنوان ادعای سنتی بیان کن.
از تشخیص بیماری داخلی از خطوط کف دست خودداری کن.
در پایان بنویس: «این نتیجه فقط یک احتمال و تفسیر غیرتشخیصی است.»
""".trimIndent()

        Section.TRADITIONAL -> """
پاسخ‌های پرسشنامه طب سنتی را تحلیل کن. خروجی را به دو بخش جدا تقسیم کن:
1) الگوهای TCM مانند Heat, Cold, Dampness, Qi deficiency, Blood stasis
2) الگوهای Ayurveda مانند Vata, Pitta, Kapha
این خروجی تشخیص پزشکی نیست. الگوهای محتمل را همراه با دلیل و توصیه‌های کم‌خطر عمومی مثل خواب، آب کافی و مراجعه در صورت علائم پایدار توضیح بده.
در پایان بنویس: «این نتیجه فقط یک احتمال و تفسیر غیرتشخیصی است.»

پاسخ‌ها:
$extractedText
""".trimIndent()
    }

    fun localLabSummary(text: String): String {
        val pattern = Regex(
            """(?im)^\s*([A-Za-z][A-Za-z0-9 ()/%+_.-]{1,35})\s+([0-9]+(?:\.[0-9]+)?)\s*([A-Za-z/%µμ0-9^.-]*)\s+([0-9]+(?:\.[0-9]+)?)\s*[-–]\s*([0-9]+(?:\.[0-9]+)?)"""
        )
        val findings = pattern.findAll(text).mapNotNull { m ->
            val name = m.groupValues[1].trim()
            val value = m.groupValues[2].toDoubleOrNull() ?: return@mapNotNull null
            val unit = m.groupValues[3].trim()
            val low = m.groupValues[4].toDoubleOrNull() ?: return@mapNotNull null
            val high = m.groupValues[5].toDoubleOrNull() ?: return@mapNotNull null
            val flag = when {
                value < low -> "پایین"
                value > high -> "بالا"
                else -> "داخل محدوده"
            }
            "• $name: $value $unit — $flag (مرجع $low–$high)"
        }.take(40).toList()

        return if (findings.isEmpty()) {
            "OCR انجام شد، اما ردیف‌های دارای «مقدار + محدوده مرجع» با اطمینان کافی پیدا نشدند. برای تحلیل دقیق‌تر از AI استفاده کن یا تصویر واضح‌تری بگیر."
        } else {
            "خلاصه محلی بر اساس محدوده‌های مرجع خود گزارش:\n" + findings.joinToString("\n") +
                "\n\nاین خلاصه صرفاً آموزشی است و تفسیر نهایی باید با زمینه بالینی انجام شود."
        }
    }
}
